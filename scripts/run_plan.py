"""
Script to execute the deterministic procurement planner and generate reports.

Outputs:
- Printed summary to console:
  1. Ranked at-risk product list
  2. Strategy comparison table (totals)
  3. Recommended procurement plan with decision reasons
- Writes reports/procurement_plan.json
- Writes reports/procurement_plan.md
"""

import json
import os
import sys

# Ensure repository root is on sys.path
REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

from tools.procurement_planner import build_procurement_plan

REPORTS_DIR = os.path.join(REPO_ROOT, "reports")


def generate_markdown_report(plan: dict) -> str:
    """Generate a clean GitHub-flavored markdown report of the procurement plan."""
    md = []
    md.append("# StockPilot Procurement & Replenishment Plan")
    md.append("")
    md.append("Generated by StockPilot Autonomous Supply Chain Decision Agent.")
    md.append("")

    # 1. Product Inventory Status
    md.append("## 1. Ranked Product Inventory & Risk Status")
    md.append("")
    md.append("| Product ID | Name | Category | Current Stock | Daily Demand | Days of Cover | Risk Level | Action |")
    md.append("|:---|:---|:---|:---:|:---:|:---:|:---:|:---|")
    for p in plan["products"]:
        md.append(
            f"| **{p['product_id']}** | {p['name']} | {p['category']} | {p['current_stock']} | "
            f"{p['daily_demand']:.2f} | {p['days_of_cover']:.2f} | `{p['risk_level']}` | {p['action']} |"
        )
    md.append("")

    # 2. Strategy Comparison Table
    md.append("## 2. Procurement Strategy Comparison")
    md.append("")
    md.append("| Strategy | Total Purchasing Cost ($) | Avg Lead Time (Days) | Total Units Short Before Arrival | Critical / High Products |")
    md.append("|:---|:---:|:---:|:---:|:---:|")

    strat_map = [
        ("Cheapest (Cost Minimization)", plan["strategies"]["cheapest"]["totals"]),
        ("Fastest (Lead-Time Minimization)", plan["strategies"]["fastest"]["totals"]),
        ("Recommended (Balanced Risk & Cost)", plan["strategies"]["recommended"]["totals"]),
    ]
    for sname, t in strat_map:
        md.append(
            f"| **{sname}** | ${t['total_cost']:,.2f} | {t['average_lead_time']:.1f}d | "
            f"{t['total_units_short']:.1f} units | {t['critical_or_high_count']} |"
        )
    md.append("")

    # 3. Recommended Plan Details
    md.append("## 3. Recommended Procurement Orders & Decision Reasoning")
    md.append("")
    md.append("| Product ID | Supplier ID | Supplier Name | Order Qty | Unit Lead Time | Total Cost ($) | Shortfall | Decision Reason |")
    md.append("|:---|:---|:---|:---:|:---:|:---:|:---:|:---|")
    for o in plan["strategies"]["recommended"]["orders"]:
        md.append(
            f"| **{o['product_id']}** | {o['supplier_id']} | {o['supplier_name']} | {o['order_qty']} | "
            f"{o['lead_time_days']}d | ${o['total_cost']:,.2f} | {o['shortfall_before_arrival']:.1f} | {o['reason']} |"
        )
    md.append("")

    return "\n".join(md)


def main():
    os.makedirs(REPORTS_DIR, exist_ok=True)

    print("=" * 95)
    print("STOCKPILOT DETERMINISTIC PROCUREMENT PLANNER")
    print("=" * 95)

    plan = build_procurement_plan(horizon_days=7, coverage_days=14)
    if "error" in plan:
        print(f"Error building plan: {plan['error']}")
        sys.exit(1)

    # 1. Print Ranked At-Risk Product List
    print("\n1. RANKED PRODUCT INVENTORY STATUS (by Urgency and Days of Cover)")
    print("-" * 95)
    print(f"{'ID':<6} {'Product Name':<35} {'Stock':<7} {'Demand/d':<10} {'Days Cover':<12} {'Risk':<10} {'Action':<15}")
    print("-" * 95)
    for p in plan["products"]:
        print(
            f"{p['product_id']:<6} {p['name']:<35} {p['current_stock']:<7} {p['daily_demand']:<10.2f} "
            f"{p['days_of_cover']:<12.2f} {p['risk_level']:<10} {p['action']:<15}"
        )

    # 2. Print Strategy Comparison Table
    print("\n2. PORTFOLIO STRATEGY COMPARISON")
    print("-" * 95)
    print(f"{'Strategy':<30} {'Total Cost ($)':<18} {'Avg Lead Time':<16} {'Units Short':<15} {'Crit/High Count':<16}")
    print("-" * 95)
    for sname, key in [("Cheapest Strategy", "cheapest"), ("Fastest Strategy", "fastest"), ("Recommended Plan", "recommended")]:
        tot = plan["strategies"][key]["totals"]
        print(
            f"{sname:<30} ${tot['total_cost']:<17,.2f} {tot['average_lead_time']:<15.2f}d "
            f"{tot['total_units_short']:<14.2f} {tot['critical_or_high_count']:<16}"
        )

    # 3. Print Recommended Plan Details with Reasoning
    print("\n3. RECOMMENDED PROCUREMENT ACTION PLAN")
    print("-" * 95)
    print(f"{'ID':<6} {'Supplier':<10} {'Qty':<7} {'Lead':<7} {'Cost ($)':<12} {'Short':<8} {'Reason':<45}")
    print("-" * 95)
    for o in plan["strategies"]["recommended"]["orders"]:
        print(
            f"{o['product_id']:<6} {o['supplier_id']:<10} {o['order_qty']:<7} {o['lead_time_days']:<4}d "
            f"${o['total_cost']:<11,.2f} {o['shortfall_before_arrival']:<8.1f} {o['reason']}"
        )

    # 4. Save JSON and Markdown artifacts
    json_path = os.path.join(REPORTS_DIR, "procurement_plan.json")
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(plan, f, indent=2)

    md_path = os.path.join(REPORTS_DIR, "procurement_plan.md")
    md_content = generate_markdown_report(plan)
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(md_content)

    print("\n" + "=" * 95)
    print(f"Reports successfully written:")
    print(f" - JSON: {json_path}")
    print(f" - Markdown: {md_path}")
    print("=" * 95)


if __name__ == "__main__":
    main()

